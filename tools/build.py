#!/usr/bin/env python3
"""Compile macros/<class>/*.macro into the ClassMacros addon.

Usage:
    python3 tools/build.py [--interface 11200] [--install <AddOns dir>] [--zip]
"""
import argparse
import re
import shutil
import sys
import zipfile
from pathlib import Path

# Client limits. Adjust here if WoW: Forever differs from 1.12.
MAX_BODY = 255
MAX_NAME = 16
MAX_PER_CHARACTER = 18
DEFAULT_INTERFACE = "11200"

CLASSES = ("druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior")
PLACEHOLDER = re.compile(r"<([^<>\n]*)>")

ROOT = Path(__file__).resolve().parent.parent
MACROS_DIR = ROOT / "macros"
ADDON_SRC = ROOT / "addon" / "ClassMacros"
DIST = ROOT / "dist"
OUT = DIST / "ClassMacros"


def name_from_filename(path):
    return " ".join(part.capitalize() for part in path.stem.split("-"))


def parse_macro(path, errors):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    lines = text.rstrip("\n").split("\n")
    name = name_from_filename(path)
    if lines and lines[0].startswith("#name "):
        name = lines.pop(0)[len("#name "):].strip()
    body = "\n".join(lines)
    rel = path.relative_to(ROOT)

    if not body.strip():
        errors.append(f"{rel}: macro body is empty")
    if len(name) > MAX_NAME:
        errors.append(f"{rel}: name '{name}' is {len(name)} chars (max {MAX_NAME}); add a '#name <short>' first line")
    if len(body) > MAX_BODY:
        errors.append(f"{rel}: body is {len(body)} chars (max {MAX_BODY})")
    for lineno, line in enumerate(lines, 1):
        for match in PLACEHOLDER.finditer(line):
            if not match.group(1).strip():
                errors.append(f"{rel}:{lineno}: empty placeholder '<>'")
        if line.count("<") != line.count(">"):
            errors.append(f"{rel}:{lineno}: unbalanced '<' / '>'")

    placeholders = sorted({m.group(1).strip() for m in PLACEHOLDER.finditer(body) if m.group(1).strip()})
    return {"name": name, "body": body, "placeholders": placeholders}


def collect(errors):
    data = {}
    for class_dir in sorted(p for p in MACROS_DIR.iterdir() if p.is_dir()):
        if class_dir.name not in CLASSES:
            errors.append(f"{class_dir.relative_to(ROOT)}: unknown class folder (expected one of {', '.join(CLASSES)})")
            continue
        macros = [parse_macro(p, errors) for p in sorted(class_dir.glob("*.macro"))]
        if len(macros) > MAX_PER_CHARACTER:
            errors.append(f"{class_dir.relative_to(ROOT)}: {len(macros)} macros (max {MAX_PER_CHARACTER} per character)")
        seen = set()
        for m in macros:
            if m["name"].lower() in seen:
                errors.append(f"{class_dir.relative_to(ROOT)}: duplicate macro name '{m['name']}'")
            seen.add(m["name"].lower())
        data[class_dir.name.upper()] = macros
    return data


def lua_string(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{out}"'


def render_lua(data):
    lines = ["-- Generated by tools/build.py. Do not edit; edit macros/<class>/*.macro instead.", "ClassMacros_Data = {"]
    for cls, macros in data.items():
        lines.append(f"  {cls} = {{")
        for m in macros:
            ph = ", ".join(lua_string(p) for p in m["placeholders"])
            lines.append(f"    {{ name = {lua_string(m['name'])}, body = {lua_string(m['body'])}, placeholders = {{ {ph} }} }},")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--interface", default=DEFAULT_INTERFACE, help="TOC Interface number (default %(default)s)")
    parser.add_argument("--install", metavar="ADDONS_DIR", help="copy the built addon into this Interface/AddOns folder")
    parser.add_argument("--zip", action="store_true", help="also write dist/ClassMacros.zip")
    args = parser.parse_args()

    errors = []
    data = collect(errors)
    if errors:
        print("Build failed:", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
        return 1

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    toc = (ADDON_SRC / "ClassMacros.toc").read_text(encoding="utf-8").replace("@INTERFACE@", args.interface)
    (OUT / "ClassMacros.toc").write_text(toc, encoding="utf-8")
    shutil.copy2(ADDON_SRC / "Core.lua", OUT / "Core.lua")
    (OUT / "Macros.lua").write_text(render_lua(data), encoding="utf-8")

    for cls, macros in data.items():
        print(f"  {cls:<8} {len(macros):>2} macros")
    print(f"Built {OUT.relative_to(ROOT)} (Interface {args.interface})")

    if args.zip:
        zip_path = DIST / "ClassMacros.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in sorted(OUT.iterdir()):
                zf.write(f, f"ClassMacros/{f.name}")
        print(f"Wrote {zip_path.relative_to(ROOT)}")

    if args.install:
        dest = Path(args.install).expanduser() / "ClassMacros"
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(OUT, dest)
        print(f"Installed to {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
